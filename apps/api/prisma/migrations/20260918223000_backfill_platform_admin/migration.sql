-- =============================================================================
--  回填：把种子账号恢复为平台管理员
-- =============================================================================
--
-- 背景：seed.ts 一直把种子账号视为"系统管理员"（老 schema 上它的 role 是 OWNER），
--   但 isPlatformAdmin 是这次迁移才新增的列，默认 false —— 于是升级后
--   这个账号失去了平台管理员的身份，而它是系统里唯一能管理成员的账号。
--
-- ★ 为什么不能靠重新跑 seed 解决：
--   seed 是幂等的 upsert，跑一遍确实会把它设回 true。但生产升级流程里
--   **不一定会重跑 seed**（那是灌演示数据用的），所以必须在迁移里修掉。
--
-- ★ 为什么只按邮箱精确匹配：
--   平台管理员是"能跨主体查看"的高权限身份，绝不能靠"角色像管理员"之类的
--   模糊条件批量授予 —— 那会把普通实控人也提权。这里只认种子脚本写死的那个邮箱。
UPDATE "app_user"
SET "isPlatformAdmin" = true
WHERE "email" = 'admin@bookkeeper.local'
  AND "isPlatformAdmin" = false;
