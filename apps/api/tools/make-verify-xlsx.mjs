/**
 * 生成验证用的真实 Excel 财务报表
 * ============================================================
 * 为什么要真生成 xlsx 而不是写 CSV：
 *   财报绝大多数来自代账公司的 Excel，而 Excel 与 CSV 的读取路径**完全不同**
 *   （exceljs 遍历工作表 vs 手写 RFC4180 解析器）。
 *   只测 CSV 等于没测 Excel 那条路，而用户实际用的就是 Excel。
 *
 * 生成的表刻意带上真实报表的各种"脏"特征：
 *   · 前两行是标题与表头说明（"会小企01表"、"单位：元"）
 *   · 项目名带序号前缀（"一、流动资产："、"（一）货币资金"）
 *   · 有合计行（"流动资产合计"、"资产总计"）—— 这些绝不能被映射到科目
 *   · 有"减：累计折旧"这种带方向的行
 *   · 有 0 值行与空行
 *   · 合计行用公式（result 缓存）—— 报表里合计基本都是公式
 */
import ExcelJS from 'exceljs';
import { mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const outPath = resolve(process.argv[2] ?? 'apps/api/tmp/verify-balance-sheet.xlsx');
mkdirSync(dirname(outPath), { recursive: true });

const wb = new ExcelJS.Workbook();
const ws = wb.addWorksheet('资产负债表');

// ── 标题区 ──
ws.addRow(['资产负债表']);
ws.addRow(['会小企01表']);
ws.addRow(['编制单位：演示科技有限公司', '', '2024年12月31日', '', '单位：元']);
ws.addRow([]);
ws.addRow(['项目', '行次', '期末余额', '年初余额']);

// ── 数据行：[项目, 行次, 期末, 年初]；合计行用公式 ──
