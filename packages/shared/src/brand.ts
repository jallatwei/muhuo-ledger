/**
 * 品牌与命名 —— 唯一声明处
 * ============================================================
 * 产品名要与配色同源：主色取自用神、辅色取自喜神，
 * 名字里也就带着这两个五行。改喜用时，这个名字与配色一起改。
 *
 * ★ 为什么抽成常量而不是各处写字符串：
 *   产品名出现在登录页品牌区、侧边栏 Logo、页面标题、导出文件名里。
 *   散着写的话，改一次名字必然漏掉几处 —— 而"同一屏里出现两个名字"
 *   是很显眼的低级错误。
 *
 * 命理依据见 docs/主题配色-八字喜用.md。
 */

/**
 * 产品名。
 *
 * 「木火账房」的取法：
 *   · **木火** —— 本命日主丙火生于丑月（腊月）天寒地冻，非木不生。
 *     木为用神、火为喜神，正是界面上那两个主色的来源。
 *   · **账房** —— 旧时管账之处。比「记账」有分量，又比「财务云」朴实，
 *     与小企业自用的定位相称。
 *
 * 名字与实际配色是**可互相印证**的：打开界面看到的主色就是松绿（木）、
 * 辅色就是赤陶（火），不需要额外解释。
 */
export const APP_NAME = '木火账房';

/**
 * 一句话说明。用于登录页品牌区与页面描述。
 *
 * ★ 措辞上刻意不承诺"助财"这类效果 —— 记账软件的价值是**把账记对**，
 *   财是经营结果，不是配色能给的。这里的说法是"顺其性"而非"改其命"，
 *   既不糊弄人，也确实是这套配色存在的理由。
 */
export const APP_TAGLINE = '木火相生，顺其性而理其财';

/** 副标题：说清这是什么软件 */
export const APP_SUBTITLE = '小企业自动记账 · 小企业会计准则 · 一般纳税人';

/** 品牌名的拆色：前两字各取一个喜用五行色 */
export const APP_NAME_PARTS = [
  { text: '木', token: 'wood500' },
  { text: '火', token: 'fire500' },
  { text: '账房', token: null },
] as const;
